// Quick screenshots of the real app screen against the dev server.
import { createRequire } from "module";
const require = createRequire(import.meta.url);
const puppeteer = require("puppeteer");
const BASE = process.env.BASE || "http://127.0.0.1:4231/";
const OUT = process.argv[2];
const theme = process.argv[3] || "light";
const b = await puppeteer.launch({ headless: true, args: ["--no-sandbox"] });
const p = await b.newPage();
const errs = [];
p.on("pageerror", e => errs.push(String(e)));
p.on("dialog", d => { errs.push("NATIVE DIALOG: " + d.message()); d.dismiss(); });
await p.emulateMediaFeatures([{ name: "prefers-color-scheme", value: theme }]);
await p.setViewport({ width: 400, height: 860, deviceScaleFactor: 1 });
const wait = ms => new Promise(r => setTimeout(r, ms));
const shot = async n => { await wait(400); await p.screenshot({ path: `${OUT}/${theme}-${n}.png` }); };
await p.goto(BASE); await shot("1-home");
await p.click("#home-open"); await wait(500); await shot("2-picker");
await p.evaluate(() => [...document.querySelectorAll("#pick-list .row")].find(r => r.textContent.includes("Cat photos.zip")).click()); await wait(700);
await shot("3-open");
await p.evaluate(() => [...document.querySelectorAll("#o-list .row")].find(r => r.textContent.includes("Cat photos")).click()); await wait(300);
await p.evaluate(() => [...document.querySelectorAll("#o-list .row")].find(r => r.textContent.includes("2026")).click()); await wait(300);
await p.evaluate(() => [...document.querySelectorAll("#o-list .row")].find(r => r.textContent.includes("hello.png")).click()); await wait(900);
await shot("4-preview");
await p.click("#pv-close"); await p.click("#o-all"); await wait(1200); await shot("5-done");
await p.click("#go-home"); await p.click("#home-make"); await wait(300);
await p.click("#m-add-files"); await wait(500);
await p.click("#pick-up"); await wait(400);
await p.evaluate(() => [...document.querySelectorAll("#pick-list .row")].find(r => r.textContent.includes("Pictures")).click()); await wait(400);
await p.evaluate(() => [...document.querySelectorAll("#pick-list .row input")].forEach(c => c.click())); await shot("6-pick-items");
await p.click("#pick-ok"); await wait(500);
await p.click("#m-pw-on"); await p.type("#m-pw", "purr"); await p.type("#m-pw2", "purr");
await p.click('#m-format button[data-v="SevenZ"]'); await shot("7-make");
await p.click("#home-open").catch(() => {});
await p.goto(BASE); await p.click("#home-open"); await wait(400);
await p.evaluate(() => [...document.querySelectorAll("#pick-list .row")].find(r => r.textContent.includes("Secret plans")).click()); await wait(600);
await shot("8-password");
console.log(JSON.stringify({ errs }));
await b.close();
